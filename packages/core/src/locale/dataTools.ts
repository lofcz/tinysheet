const translations: Record<string, DeepPartial<DataToolsLocale>> = {
  en,
  zh,
  "zh-CN": zh,
  "zh-TW": zhTW,
  es,
  ru,
  hi,
};

const cache: Record<string, DataToolsLocale> = {};

function mergeDeep(base: any, over: any): any {
  if (over == null) return base;
  if (Array.isArray(base)) return Array.isArray(over) ? over : base;
  if (typeof base !== "object") return over ?? base;
  const out: any = {};
  Object.keys(base).forEach((k) => {
    out[k] = mergeDeep(base[k], over[k]);
  });
  return out;
}

/** The data tools strings for a context's language (English fallback). */
export function dataToolsLocale(ctx: {
  lang?: string | null;
}): DataToolsLocale {
  const lang = ctx?.lang || "en";
  const key = [lang, lang.split("-")[0]].find((l) => l in translations) ?? "en";
  if (!cache[key]) cache[key] = mergeDeep(en, translations[key]);
  return cache[key];
}

/** Replace {name} placeholders in a locale string. */
export function formatLocaleText(
  text: string,
  values: Record<string, string | number>
) {
  return text.replace(/\{(\w+)\}/g, (m, k) =>
    k in values ? `${values[k]}` : m
  );
}
