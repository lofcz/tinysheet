export type ChartToolsLocale = typeof en;

const translations: Record<string, Partial<ChartToolsLocale>> = {};

const cache: Record<string, ChartToolsLocale> = {};

/** The chart tools strings for a context's language (English fallback). */
export function chartToolsLocale(ctx: {
  lang?: string | null;
}): ChartToolsLocale {
  const lang = ctx?.lang || "en";
  const key = [lang, lang.split("-")[0]].find((l) => l in translations) ?? "en";
  if (!cache[key]) cache[key] = { ...en, ...translations[key] };
  return cache[key];
}
