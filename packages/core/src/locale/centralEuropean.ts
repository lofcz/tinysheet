const vocabulary = new Map(
  rows
    .trim()
    .split("\n")
    .map((row) => {
      const [en, cs, sk, pl] = row.split("|");
      return [en, [cs, sk, pl]] as const;
    })
);

/** Translate known shared labels; preserve numbers, formulas and unknown keys. */
export function centralEuropeanUi<T>(base: T, lang: "cs" | "sk" | "pl"): T {
  const index = { cs: 0, sk: 1, pl: 2 }[lang];
  const visit = (value: unknown): unknown => {
    if (typeof value === "string") {
      const direct = vocabulary.get(value)?.[index];
      if (direct) return direct;
      const shortcut = /^(.*?)( \((?:Ctrl|Alt|Shift)[^)]*\))$/.exec(value);
      return shortcut && vocabulary.has(shortcut[1])
        ? vocabulary.get(shortcut[1])![index] + shortcut[2]
        : value;
    }
    if (Array.isArray(value)) return value.map(visit);
    if (value && typeof value === "object")
      return Object.fromEntries(
        Object.entries(value).map(([key, child]) => [
          key,
          key === "functionlist" ? child : visit(child),
        ])
      );
    return value;
  };
  return visit(base) as T;
}
