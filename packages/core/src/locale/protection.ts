const translations: Record<string, DeepPartial<ProtectionLocale>> = {
  en,
  zh,
  "zh-CN": zh,
  "zh-TW": zhTW,
  es,
  ru,
  hi,
};

const cache: Record<string, ProtectionLocale> = {};

function mergeDeep(base: any, over: any): any {
  if (over == null) return base;
  if (typeof base !== "object" || Array.isArray(base)) return over ?? base;
  const out: any = {};
  Object.keys(base).forEach((k) => {
    out[k] = mergeDeep(base[k], over[k]);
  });
  return out;
}

/** Protection and View strings for a context's language (English fallback). */
export function protectionLocale(ctx: {
  lang?: string | null;
}): ProtectionLocale {
  const lang = ctx?.lang || "en";
  const key = [lang, lang.split("-")[0]].find((l) => l in translations) ?? "en";
  if (!cache[key]) cache[key] = mergeDeep(en, translations[key]);
  return cache[key];
}
